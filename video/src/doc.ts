/**
 * 「いつものやり方」側の URL。
 * RFC 2606 の予約ドメインを使う。実在サービスを模すと誤解と権利の両方で問題になるうえ、
 * ここに notes.rou39.com を出すと **Stash Notes がログインを求めるように見えてしまう**。
 */
export const LOGIN_URL = 'example.com/login';

/**
 * 端末の枠の幅。
 * 高さは (字幕 140 + 端末 ≒ 幅 × 1.2) なので、比率ごとのセーフエリアに収まる上限まで寄せる。
 * 小さいと余白ばかりになり、画面の変化量も小さくなって「動いていない」ように見える。
 */
export const deviceWidth = (l: Layout) => (l.isTall ? 760 : l.isWide ? 630 : 610);

/** 17 文字が枠に収まり かつ 13 行が画面に収まる比率 */
export const docFontSize = (deviceW: number) => deviceW * 0.042;

/** 3 桁ごとにカンマ。toLocaleString はレンダラ差が出るので自前で組む */
export const withComma = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
